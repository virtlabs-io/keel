/**
 * @file test_proxy_e2e.c
 * @brief Full-stack proxy integration tests with real process orchestration.
 *
 * This suite boots KEEL as a child process, drives traffic through the proxy,
 * and validates external behavior from the client side. It therefore exercises
 * cross-layer integration that unit tests cannot observe in isolation: runtime
 * config loading, worker startup, backend probing, auth flow, and query routing
 * under a live parent/child process lifecycle.
 *
 * The tests deliberately favor deterministic orchestration over maximal load.
 * Their value is confidence that the assembled system starts, accepts traffic,
 * and shuts down cleanly across repeated runs.
 */

