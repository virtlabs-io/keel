/**
 * @brief Locate an executable KEEL proxy binary in common build/runtime paths.
 * @return Absolute or relative executable path, or `NULL` if not found.
 */
static const char* find_proxy_binary(void) {
    static char path[PATH_MAX];
    
    /* Try relative paths from test binary location */
    const char* candidates[] = {
        "../src/main/keel",           /* In build/tests/ */
        "../../build/src/main/keel",   /* In source/tests/ */
        "./keel",                       /* Current dir */
        NULL
    };
    
    for (int i = 0; candidates[i]; i++) {
        if (access(candidates[i], X_OK) == 0) {
            /* Get absolute path */
            if (realpath(candidates[i], path)) {
                return path;
            }
            return candidates[i];
        }
    }
    
    /* Try PATH */
    FILE* fp = popen("which keel 2>/dev/null", "r");
    if (fp) {
        if (fgets(path, sizeof(path), fp)) {
            path[strcspn(path, "\n")] = '\0';
            pclose(fp);
            if (access(path, X_OK) == 0) {
                return path;
            }
        }
        pclose(fp);
    }
    
    return NULL;
}

/**
 * @brief Generate a runtime config wired to the currently discovered test
 *        cluster endpoints.
 * @param out_path [out] Receives the config path.
 * @param out_path_len Capacity of `out_path`.
 * @return `true` on success, `false` otherwise.
 *
 * Generating this file at runtime avoids stale endpoint assumptions and keeps
 * the proxy e2e suite aligned with whatever ports the integration harness has
 * actually selected for primary and replicas.
 */
static bool write_runtime_config(char* out_path, size_t out_path_len) {
    FILE* fp = fopen(KEEL_RUNTIME_CONFIG_FILE, "w");
    if (!fp) {
        fprintf(stderr, "ERROR: failed to create runtime config %s: %s\n",
                KEEL_RUNTIME_CONFIG_FILE, strerror(errno));
        return false;
    }

    fprintf(fp,
        "# Auto-generated by test_proxy_e2e.c\n"
        "[keel]\n"
        "log_level = 3\n\n"
        "[worker_group.myapp]\n"
        "name = test\n"
        "bind_addr = 127.0.0.1\n"
        "bind_port = %d\n"
        "num_workers = 2\n"
        "worker_strategy = fixed\n"
        "distribution = round_robin\n"
        "max_conns_per_worker = 100\n"
        "max_conns_total = 200\n"
        "client_idle_timeout = 30s\n"
        "client_connect_timeout = 10s\n"
        "buffer_pool_size = 64MB\n"
        "arena_size = 32KB\n\n"
        "pool_mode = transaction\n"
        "min_pool_size = 2\n"
        "max_pool_size = 10\n"
        "idle_timeout = 30s\n"
        "query_timeout = 30s\n\n"
        "probe = postgres\n"
        "probe_interval = 2s\n"
        "probe_timeout = 2s\n"
        "probe_retries = 2\n"
        "failover_delay = 5s\n\n"
        "server_user = postgres\n"
        "server_password = postgres\n"
        "server_auth = scram-sha-256\n\n"
        "[worker_group.myapp.servers]\n"
        "primary  = host=%s port=%u dbname=postgres role=primary weight=100\n"
        "replica1 = host=%s port=%u dbname=postgres role=replica weight=100\n"
        "replica2 = host=%s port=%u dbname=postgres role=replica weight=100\n",
        KEEL_PROXY_PORT,
        integ_get_node_host(1), integ_get_node_port(1),
        integ_get_node_host(2), integ_get_node_port(2),
        integ_get_node_host(3), integ_get_node_port(3));
    fclose(fp);

    strncpy(out_path, KEEL_RUNTIME_CONFIG_FILE, out_path_len - 1);
    out_path[out_path_len - 1] = '\0';
    return true;
}

/**
 * @brief Materialize and return the runtime config path for proxy startup.
 * @return Config path on success, otherwise `NULL`.
 */
static const char* find_config_file(void) {
    static char path[512];
    if (write_runtime_config(path, sizeof(path)))
        return path;
    return NULL;
}

/**
 * @brief Fork and start the KEEL proxy, then poll readiness via real client
 *        connections.
 * @return `true` if the proxy becomes query-ready before timeout.
 *
 * Readiness is defined as successful connect plus `SELECT 1`, not just process
 * liveness. This avoids false positives where the process exists but workers or
 * backend probing are not yet operational.
 */
static bool start_proxy(void) {
    const char* binary = find_proxy_binary();
    if (!binary) {
        fprintf(stderr, "ERROR: KEEL proxy binary not found\n");
        fprintf(stderr, "       Build the project first: cmake --build build\n");
        return false;
    }
    
    const char* config = find_config_file();
    if (!config) {
        fprintf(stderr, "ERROR: Test config file not found: %s\n", KEEL_CONFIG_FILE);
        return false;
    }
    
    printf("Starting proxy: %s -c %s\n", binary, config);
    
    pid_t pid = fork();
    if (pid < 0) {
        fprintf(stderr, "ERROR: fork() failed: %s\n", strerror(errno));
        return false;
    }
    
    if (pid == 0) {
        /* Child process - exec the proxy */
        /* Redirect stdout/stderr to log file */
        if (!freopen("/tmp/keel_test.log", "w", stdout) ||
            !freopen("/tmp/keel_test.log", "a", stderr)) {
            _exit(2);
        }
        
        execl(binary, "keel", "-c", config, NULL);
        
        /* exec failed */
        fprintf(stderr, "ERROR: exec failed: %s\n", strerror(errno));
        _exit(1);
    }
    
    /* Parent process */
    g_proxy_pid = pid;
    
    /* Wait for proxy to be ready */
    for (int i = 0; i < PROXY_START_TIMEOUT_SEC; i++) {
        sleep(1);
        
        /* Check if process is still running */
        int status;
        pid_t result = waitpid(pid, &status, WNOHANG);
        if (result == pid) {
            /* Process exited */
            fprintf(stderr, "ERROR: Proxy exited prematurely with status %d\n", 
                    WEXITSTATUS(status));
            fprintf(stderr, "       Check /tmp/keel_test.log for details\n");
            g_proxy_pid = 0;
            return false;
        }
        
        /* Try to connect to proxy */
        integ_pg_conn_t* conn = integ_pg_connect(
            "127.0.0.1", KEEL_PROXY_PORT,
            TEST_USER, TEST_PASSWORD, TEST_DATABASE
        );
        
        if (conn) {
            bool ok = integ_pg_exec(conn, "SELECT 1");
            integ_pg_close(conn);
            if (ok) {
                printf("Proxy ready after %d seconds\n", i + 1);
                return true;
            }
        }
        
        printf("Waiting for proxy... (%d/%d)\n", i + 1, PROXY_START_TIMEOUT_SEC);
    }
    
    fprintf(stderr, "ERROR: Proxy did not become ready in %d seconds\n", 
            PROXY_START_TIMEOUT_SEC);
    fprintf(stderr, "       Check /tmp/keel_test.log for details\n");
    
    /* Kill the hung process */
    kill(pid, SIGTERM);
    sleep(1);
    kill(pid, SIGKILL);
    waitpid(pid, NULL, 0);
    g_proxy_pid = 0;
    
    return false;
}

/**
 * @brief Gracefully stop the proxy process with a forced-kill fallback.
 * @return
 */
static void stop_proxy(void) {
    if (g_proxy_pid <= 0) return;
    
    printf("Stopping proxy (PID %d)...\n", g_proxy_pid);
    
    /* Send SIGTERM first for graceful shutdown */
    kill(g_proxy_pid, SIGTERM);
    
    /* Wait for process to exit */
    for (int i = 0; i < PROXY_STOP_TIMEOUT_SEC; i++) {
        int status;
        pid_t result = waitpid(g_proxy_pid, &status, WNOHANG);
        if (result == g_proxy_pid) {
            printf("Proxy stopped (exit status %d)\n", WEXITSTATUS(status));
            g_proxy_pid = 0;
            return;
        }
        sleep(1);
    }
    
    /* Force kill */
    printf("Force killing proxy...\n");
    kill(g_proxy_pid, SIGKILL);
    waitpid(g_proxy_pid, NULL, 0);
    g_proxy_pid = 0;
}

/* ============================================================================
 * Test Setup/Teardown
 * ============================================================================ */

static void setup(void) {
    if (!integ_cluster_running()) {
        if (!integ_docker_available()) {
            printf("SKIP: Docker not available and no live cluster detected\n");
            g_skip_tests = true;
            return;
        }

        printf("Starting PostgreSQL cluster via Docker...\n");
        if (!integ_cluster_start(true)) {
            printf("SKIP: Failed to start PostgreSQL cluster\n");
            g_skip_tests = true;
            return;
        }
        g_cluster_started_by_test = true;
        printf("PostgreSQL cluster started\n");
    } else {
        printf("PostgreSQL cluster already running\n");
    }
    
    /* Start the KEEL proxy */
    if (!start_proxy()) {
        printf("SKIP: Failed to start KEEL proxy\n");
        g_skip_tests = true;
        return;
    }
    
    printf("\n=== Test environment ready ===\n");
    printf("PostgreSQL primary: %s:%u\n", integ_get_primary_host(), integ_get_primary_port());
    printf("KEEL proxy:          127.0.0.1:%d\n\n", KEEL_PROXY_PORT);
}

static void teardown(void) {
    stop_proxy();
    
    if (g_cluster_started_by_test) {
        printf("Stopping PostgreSQL cluster...\n");
        integ_cluster_stop(false);  /* Keep volumes for faster restart */
    }
}

