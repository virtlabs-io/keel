/* ---------------------------------------------------------------------------
 * Edge-case stress tests (Phase 2 validation priorities §20.5)
 * ---------------------------------------------------------------------------
 * These exercise the most subtle SSV interactions: ugly transaction-end
 * sequences mixing SET LOCAL, PREPARE, temp DDL, ROLLBACK, and replay
 * on a potentially different backend.
 * ---------------------------------------------------------------------------*/

/**
 * The exact sequence called out as the highest-risk edge case:
 *   BEGIN → SET LOCAL datestyle → PREPARE → temp DDL → ROLLBACK
 * After ROLLBACK both the SET LOCAL overlay AND the temp table must revert,
 * and executing the prepared stmt on a new backend must use the session-level
 * DateStyle (not the rolled-back local overlay).
 */
static void test_ssv_ugly_begin_setlocal_prepare_tempdll_rollback(void)
{
    TEST_BEGIN("proxy SSV: BEGIN + SET LOCAL + PREPARE + temp DDL + ROLLBACK replay");

    if (g_skip_tests) { printf("SKIP\n"); return; }

    integ_pg_conn_t* conn = connect_proxy();
    TEST_ASSERT_NOT_NULL(conn);
    if (!conn) return;

    /* Baseline: session-level DateStyle = ISO, MDY (month-first) */
    assert_exec_ok(conn, "SET DateStyle TO 'ISO, MDY'");

    /* Create a permanent target so we can also check temp-shadow reversion */
    assert_exec_ok(conn, "DROP TABLE IF EXISTS public.ssv_ugly_target");
    assert_exec_ok(conn, "CREATE TABLE public.ssv_ugly_target (id int)");
    assert_exec_ok(conn, "INSERT INTO public.ssv_ugly_target VALUES (1), (2), (3)");

    /* Prepare two stmts under the session-level context */
    assert_exec_ok(conn,
        "PREPARE ssv_ugly_date AS SELECT EXTRACT(MONTH FROM '01/02/2003'::date)::int");
    assert_exec_ok(conn,
        "PREPARE ssv_ugly_count AS SELECT COUNT(*) FROM ssv_ugly_target");

    /* Verify baseline */
    assert_query_int_eq(conn, "EXECUTE ssv_ugly_date", 1);   /* MDY → month=1 */
    assert_query_int_eq(conn, "EXECUTE ssv_ugly_count", 3);

    /* The ugly sequence */
    assert_exec_ok(conn, "BEGIN");
    assert_exec_ok(conn, "SET LOCAL DateStyle TO 'ISO, DMY'");
    /* DateStyle is a parse-time GUC: the PREPARE above already froze the
     * date literal under MDY.  SET LOCAL within the same pinned-backend
     * transaction does NOT re-parse, so the result stays month=1 (MDY). */
    assert_query_int_eq(conn, "EXECUTE ssv_ugly_date", 1);   /* parse-time: still MDY */
    /* Create temp table that shadows the permanent one */
    assert_exec_ok(conn, "CREATE TEMP TABLE ssv_ugly_target (id int)");
    assert_exec_ok(conn, "INSERT INTO ssv_ugly_target VALUES (1)");
    assert_query_int_eq(conn, "EXECUTE ssv_ugly_count", 1);  /* temp shadow */
    /* ROLLBACK reverts both SET LOCAL and temp table */
    assert_exec_ok(conn, "ROLLBACK");

    /* After rollback: session-level DateStyle (MDY) restored, temp gone */
    assert_query_int_eq(conn, "EXECUTE ssv_ugly_date", 1);   /* MDY → month=1 */
    assert_query_int_eq(conn, "EXECUTE ssv_ugly_count", 3);  /* permanent table */

    assert_exec_ok(conn, "DEALLOCATE ssv_ugly_date");
    assert_exec_ok(conn, "DEALLOCATE ssv_ugly_count");
    assert_exec_ok(conn, "RESET DateStyle");
    assert_exec_ok(conn, "DROP TABLE public.ssv_ugly_target");

    integ_pg_close(conn);
    TEST_END();
}

