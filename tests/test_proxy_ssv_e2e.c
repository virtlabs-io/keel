#define KEEL_PROXY_PORT 16433
#define KEEL_CONFIG_FILE "keel_ssv_test.ini"

#define TEST_USER "test"
#define TEST_PASSWORD "test"
#define TEST_DATABASE "postgres"

#define PROXY_START_TIMEOUT_SEC 10
#define PROXY_STOP_TIMEOUT_SEC 5

#define KEEL_RUNTIME_CONFIG_FILE "/tmp/keel_ssv_test_runtime.ini"

static pid_t g_proxy_pid = 0;
static bool g_cluster_started_by_test = false;
static bool g_skip_tests = false;

/**
 * @brief Locate the keel proxy binary for E2E testing.
 *
 * Searches a set of candidate build-output paths, then falls back to
 * `which keel`.  Returns NULL if no executable is found.
 *
 * @return Absolute path to the keel binary, or NULL.
 */
static const char* find_proxy_binary(void)
{
    static char path[PATH_MAX];
    const char* candidates[] = {
        "../src/main/keel",
        "../../build/src/main/keel",
        "./keel",
        NULL
    };

    for (int i = 0; candidates[i]; i++) {
        if (access(candidates[i], X_OK) == 0) {
            if (realpath(candidates[i], path))
                return path;
            return candidates[i];
        }
    }

    FILE* fp = popen("which keel 2>/dev/null", "r");
    if (fp) {
        if (fgets(path, sizeof(path), fp)) {
            path[strcspn(path, "\n")] = '\0';
            pclose(fp);
            if (access(path, X_OK) == 0)
                return path;
        }
        pclose(fp);
    }

    return NULL;
}

/**
 * @brief Generate a minimal runtime INI config for the SSV E2E tests.
 *
 * Writes a single-worker, single-backend configuration to
 * KEEL_RUNTIME_CONFIG_FILE with transaction pool mode and
 * PS-mode=tracking.  The single-backend constraint is critical:
 * it forces every backend reassignment through the DISCARD ALL +
 * replay path, making SSV correctness deterministic.
 *
 * @param out_path      [out] Receives the config file path.
 * @param out_path_len  Capacity of @p out_path.
 * @return true on success.
 */
static bool write_runtime_config(char* out_path, size_t out_path_len)
{
    FILE* fp = fopen(KEEL_RUNTIME_CONFIG_FILE, "w");
    if (!fp)
        return false;

    fprintf(fp,
        "# Auto-generated by test_proxy_ssv_e2e.c\n"
        "[keel]\n\n"
        "[worker_group.myapp]\n"
        "name = test\n"
        "bind_addr = 127.0.0.1\n"
        "bind_port = %d\n"
        "num_workers = 1\n"
        "worker_strategy = fixed\n"
        "distribution = round_robin\n"
        "max_conns_per_worker = 32\n"
        "max_conns_total = 64\n"
        "client_idle_timeout = 30s\n"
        "client_connect_timeout = 10s\n"
        "buffer_pool_size = 32MB\n"
        "arena_size = 32KB\n\n"
        "pool_mode = transaction\n"
        "min_pool_size = 1\n"
        "max_pool_size = 1\n"
        "idle_timeout = 30s\n"
        "query_timeout = 30s\n\n"
        "probe = postgres\n"
        "probe_interval = 2s\n"
        "probe_timeout = 2s\n"
        "probe_retries = 2\n"
        "probe_password = postgres\n"
        "failover_delay = 5s\n\n"
        "server_user = postgres\n"
        "server_password = postgres\n"
        "server_auth = md5\n"
        "auth_method = trust\n"
        "prepared_statement = tracking\n\n"
        "[worker_group.myapp.servers]\n"
        "primary = host=%s port=%u dbname=postgres role=primary weight=100\n",
        KEEL_PROXY_PORT,
        integ_get_node_host(1), integ_get_node_port(1));
    fclose(fp);

    strncpy(out_path, KEEL_RUNTIME_CONFIG_FILE, out_path_len - 1);
    out_path[out_path_len - 1] = '\0';
    return true;
}

/**
 * @brief Convenience: write_runtime_config() into a static buffer.
 *
 * @return Config file path, or NULL on failure.
 */
static const char* find_config_file(void)
{
    static char path[512];
    if (write_runtime_config(path, sizeof(path)))
        return path;
    return NULL;
}

/**
 * @brief Fork-exec the keel proxy and wait for it to accept connections.
 *
 * Polls the proxy listen port for up to PROXY_START_TIMEOUT_SEC seconds.
 * On success the child PID is stored in g_proxy_pid.  On timeout the
 * child is killed.
 *
 * @return true if the proxy started and accepted a test query.
 */
static bool start_proxy(void)
{
    const char* binary = find_proxy_binary();
    const char* config = find_config_file();
    if (!binary || !config)
        return false;

    pid_t pid = fork();
    if (pid < 0)
        return false;

    if (pid == 0) {
        if (!freopen("/tmp/keel_ssv_test.log", "w", stdout) ||
            !freopen("/tmp/keel_ssv_test.log", "a", stderr)) {
            _exit(2);
        }

        execl(binary, "keel", "-c", config, NULL);
        _exit(1);
    }

    g_proxy_pid = pid;
    for (int i = 0; i < PROXY_START_TIMEOUT_SEC; i++) {
        sleep(1);

        int status;
        pid_t result = waitpid(pid, &status, WNOHANG);
        if (result == pid) {
            g_proxy_pid = 0;
            return false;
        }

        integ_pg_conn_t* conn = integ_pg_connect(
            "127.0.0.1", KEEL_PROXY_PORT,
            "test", "test", "postgres");
        if (conn) {
            bool ok = integ_pg_exec(conn, "SELECT 1");
            integ_pg_close(conn);
            if (ok)
                return true;
        }
    }

    kill(pid, SIGTERM);
    sleep(1);
    kill(pid, SIGKILL);
    waitpid(pid, NULL, 0);
    g_proxy_pid = 0;
    return false;
}

/**
 * @brief Gracefully stop the keel proxy process launched by start_proxy().
 *
 * Sends SIGTERM, waits PROXY_STOP_TIMEOUT_SEC seconds, then escalates
 * to SIGKILL if still alive.
 */
static void stop_proxy(void)
{
    if (g_proxy_pid <= 0)
        return;

    kill(g_proxy_pid, SIGTERM);
    for (int i = 0; i < PROXY_STOP_TIMEOUT_SEC; i++) {
        int status;
        pid_t result = waitpid(g_proxy_pid, &status, WNOHANG);
        if (result == g_proxy_pid) {
            g_proxy_pid = 0;
            return;
        }
        sleep(1);
    }

    kill(g_proxy_pid, SIGKILL);
    waitpid(g_proxy_pid, NULL, 0);
    g_proxy_pid = 0;
}

/**
 * @brief Connect to the proxy with up to 3 retries.
 *
 * In transaction pool mode the proxy may close idle connections
 * due to DISCARD ALL + wake race; retries ride through the
 * transient state.
 *
 * @return Connected PG handle, or NULL.
 */
static integ_pg_conn_t* connect_proxy(void)
{
    /* In transaction pool mode with max_pool_size=1, the proxy may close
     * connections due to internal pool cycling (DISCARD ALL + wake race).
     * Retry with a short delay to ride through the transient state. */
    for (int attempt = 0; attempt < 10; attempt++) {
        integ_pg_conn_t* conn = integ_pg_connect("127.0.0.1", KEEL_PROXY_PORT,
                                                  TEST_USER, TEST_PASSWORD, TEST_DATABASE);
        if (!conn) {
            usleep(100000);  /* 100ms */
            continue;
        }
        if (integ_pg_exec(conn, "SELECT 1"))
            return conn;
        integ_pg_close(conn);
        usleep(100000);
    }
    return NULL;
}

/**
 * @brief Execute SQL and assert success, printing errors on failure.
 *
 * @param conn  Live PG connection.
 * @param sql   SQL statement to execute.
 */
static void assert_exec_ok(integ_pg_conn_t* conn, const char* sql)
{
    bool ok = integ_pg_exec(conn, sql);
    if (!ok)
        fprintf(stderr, "  exec FAILED: sql=[%s] err=[%s]\n", sql, integ_pg_last_error(conn));
    TEST_ASSERT(ok);
}

/* Execute SQL for cleanup/teardown — don't assert on failure since
 * pool-mode recycling may have already cleared the object. */
static void exec_cleanup(integ_pg_conn_t* conn, const char* sql)
{
    integ_pg_exec(conn, sql);
}

/**
 * @brief Execute SQL and fetch a single int64 result, asserting equality.
 *
 * @param conn      Live PG connection.
 * @param sql       Query that returns a single integer column.
 * @param expected  Expected value.
 */
static void assert_query_int_eq(integ_pg_conn_t* conn,
                                const char* sql,
                                int64_t expected)
{
    int64_t value = 0;
    bool ok = integ_pg_query_int(conn, sql, &value);
    if (!ok)
        fprintf(stderr, "  query FAILED: sql=[%s] err=[%s]\n", sql, integ_pg_last_error(conn));
    TEST_ASSERT(ok);
    TEST_ASSERT_EQ(value, expected);
}

/**
 * @brief Suite setup: ensure Docker cluster is running, then start proxy.
 *
 * Sets g_skip_tests if either step fails, causing all test functions
 * to skip gracefully rather than crash.
 */
static void setup(void)
{
    if (!integ_cluster_running()) {
        fprintf(stderr, "setup: cluster not running\n");
        if (!integ_docker_available()) {
            fprintf(stderr, "setup: docker not available\n");
            g_skip_tests = true;
            return;
        }

        if (!integ_cluster_start(true)) {
            fprintf(stderr, "setup: cluster start failed\n");
            g_skip_tests = true;
            return;
        }
        g_cluster_started_by_test = true;
    }

    if (!start_proxy()) {
        fprintf(stderr, "setup: start_proxy failed\n");
        g_skip_tests = true;
        return;
    }
}

/**
 * @brief Suite teardown: stop proxy and optionally tear down cluster.
 */
static void teardown(void)
{
    stop_proxy();
    if (g_cluster_started_by_test)
        integ_cluster_stop(false);
}

