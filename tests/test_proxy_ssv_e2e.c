/**
 * Multiple PREPARE + DEALLOCATE cycles interleaved with GUC changes.
 * Uses search_path (execute-time resolution) so that GUC changes are
 * reflected immediately even after DEALLOCATE+PREPARE cycles, without
 * depending on re-preparation (which DateStyle would require).
 */
static void test_ssv_interleaved_prepare_deallocate_guc_changes(void)
{
    TEST_BEGIN("proxy SSV: interleaved PREPARE/DEALLOCATE with GUC changes");

    if (g_skip_tests) { printf("SKIP\n"); return; }

    integ_pg_conn_t* conn = connect_proxy();
    TEST_ASSERT_NOT_NULL(conn);
    if (!conn) return;

    /* Set up two schemas with different row counts */
    assert_exec_ok(conn, "DROP SCHEMA IF EXISTS ssv_intlv_a CASCADE");
    assert_exec_ok(conn, "DROP SCHEMA IF EXISTS ssv_intlv_b CASCADE");
    assert_exec_ok(conn, "CREATE SCHEMA ssv_intlv_a");
    assert_exec_ok(conn, "CREATE SCHEMA ssv_intlv_b");
    assert_exec_ok(conn, "CREATE TABLE ssv_intlv_a.tbl (id int)");
    assert_exec_ok(conn, "CREATE TABLE ssv_intlv_b.tbl (id int)");
    assert_exec_ok(conn, "INSERT INTO ssv_intlv_a.tbl VALUES (1)");
    assert_exec_ok(conn, "INSERT INTO ssv_intlv_b.tbl VALUES (1), (2), (3)");

    assert_exec_ok(conn, "SET search_path TO ssv_intlv_a, public");

    /* First stmt under schema A */
    assert_exec_ok(conn,
        "PREPARE ssv_intlv_s1 AS SELECT COUNT(*) FROM tbl");
    assert_query_int_eq(conn, "EXECUTE ssv_intlv_s1", 1);

    /* Change to schema B, add second stmt */
    assert_exec_ok(conn, "SET search_path TO ssv_intlv_b, public");
    assert_exec_ok(conn,
        "PREPARE ssv_intlv_s2 AS SELECT COUNT(*) FROM tbl");

    /* Both stmts now resolve to schema B (search_path is execute-time) */
    assert_query_int_eq(conn, "EXECUTE ssv_intlv_s1", 3);
    assert_query_int_eq(conn, "EXECUTE ssv_intlv_s2", 3);

    /* Deallocate first, keep second */
    assert_exec_ok(conn, "DEALLOCATE ssv_intlv_s1");

    /* Change back to schema A — second stmt should now resolve to A */
    assert_exec_ok(conn, "SET search_path TO ssv_intlv_a, public");
    assert_query_int_eq(conn, "EXECUTE ssv_intlv_s2", 1);

    assert_exec_ok(conn, "DEALLOCATE ssv_intlv_s2");
    assert_exec_ok(conn, "RESET search_path");
    assert_exec_ok(conn, "DROP SCHEMA ssv_intlv_a CASCADE");
    assert_exec_ok(conn, "DROP SCHEMA ssv_intlv_b CASCADE");

    integ_pg_close(conn);
    TEST_END();
}

