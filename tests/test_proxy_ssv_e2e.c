/**
 * @file test_proxy_ssv_e2e.c
 * @brief End-to-end proxy tests for PostgreSQL semantic state virtualization.
 *
 * This suite uses a single worker and a single backend connection so stmt-set
 * mismatches deterministically force the DISCARD ALL + replay path.
 */

